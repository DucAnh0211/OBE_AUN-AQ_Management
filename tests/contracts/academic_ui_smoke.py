"""UI on disposable API :5298 / Vite :5173 only; run academic_smoke.py first."""
import json
from pathlib import Path
from playwright.sync_api import sync_playwright, expect

folder=Path('tmp/academic-test'); f=json.loads((folder/'fixture.json').read_text())
with sync_playwright() as p:
    browser=p.chromium.launch(channel='msedge',headless=True)
    page=browser.new_page(viewport={'width':1440,'height':1000}); errors=[]
    page.on('pageerror',lambda e:errors.append(str(e)))
    page.goto('http://localhost:5173/curriculum/versions/'+str(f['versionId']))
    page.get_by_label('Email',exact=True).fill('academic-admin@example.test')
    page.get_by_label('Mật khẩu',exact=True).fill('IsolatedAcademic456!')
    page.get_by_role('button',name='Đăng nhập',exact=True).click()
    expect(page.get_by_role('heading',name='Danh sách bộ môn',exact=True)).to_be_visible(timeout=20000)
    assert page.locator('tbody tr').first.locator('td').nth(1).inner_text().isdigit()
    page.get_by_role('link',name='Lớp theo học kỳ',exact=True).first.click()
    page.get_by_role('combobox',name='Đợt học',exact=True).select_option('2026-2027')
    page.get_by_role('combobox',name='Học kỳ',exact=True).select_option('2026-2027-HK1')
    page.get_by_role('button',name='Mở danh sách lớp',exact=True).click()
    page.get_by_role('button',name='Thêm lớp',exact=True).click()
    dialog=page.get_by_role('dialog')
    dialog.get_by_label('Mã lớp',exact=True).fill('UI-CLASS')
    dialog.get_by_label('Tên lớp',exact=True).fill('Lớp giao diện kiểm thử')
    dialog.get_by_role('button',name='Tạo lớp',exact=True).click()
    expect(page.get_by_role('heading',name='Lớp giao diện kiểm thử',exact=True)).to_be_visible()
    page.get_by_role('button',name='Thêm học phần vào lớp',exact=True).click()
    dialog=page.get_by_role('dialog')
    dialog.get_by_label('Tìm bộ môn',exact=True).fill('000001')
    select=dialog.get_by_role('combobox',name='Bộ môn trong CTĐT',exact=True)
    expect(select.locator('option')).to_have_count(2)
    select.select_option(str(f['courseId']))
    dialog.get_by_role('button',name='Lưu',exact=True).click()
    expect(page.locator('tbody tr')).to_have_count(1)
    assert page.locator('tbody tr').first.locator('td').first.inner_text().isdigit()
    page.screenshot(path=str(folder/'class-offerings-desktop.png'),full_page=True)
    page.goto(f"http://localhost:5173/curriculum/versions/{f['versionId']}/offerings/{f['offeringId']}/students")
    expect(page.get_by_role('link',name='Nguyễn Văn An',exact=True)).to_be_visible()
    page.get_by_role('button',name='Thêm sinh viên',exact=True).click()
    dialog=page.get_by_role('dialog')
    dialog.get_by_label('Mã sinh viên',exact=True).fill('UI0001')
    dialog.get_by_label('Họ và tên',exact=True).fill('Nguyễn Thị Giao Diện')
    dialog.get_by_role('button',name='Lưu sinh viên',exact=True).click()
    expect(page.get_by_role('link',name='Nguyễn Thị Giao Diện',exact=True)).to_be_visible()
    page.get_by_role('link',name='Nguyễn Thị Giao Diện',exact=True).click()
    page.get_by_label('Điểm QT',exact=True).fill('8.5'); page.get_by_label('Điểm THI',exact=True).fill('75')
    page.get_by_role('button',name='Lưu điểm',exact=True).click()
    expect(page.get_by_role('status')).to_contain_text('Đã lưu điểm')
    page.reload(); expect(page.get_by_label('Điểm QT',exact=True)).to_have_value('8.5')
    page.screenshot(path=str(folder/'grade-entry-desktop.png'),full_page=True)
    page.get_by_role('link',name='Danh sách sinh viên',exact=True).click()
    page.get_by_role('button',name='Import sinh viên / điểm',exact=True).click()
    dialog=page.get_by_role('dialog'); dialog.get_by_label('Hoặc dán bảng từ trang tính',exact=True).fill('MSSV\tHoTen\nUI0002\tTrần Thị Trang Tính')
    dialog.get_by_role('button',name='Xem trước và kiểm tra',exact=True).click()
    expect(dialog.get_by_role('status')).to_contain_text('Có thể nhập dữ liệu')
    page.screenshot(path=str(folder/'import-preview-desktop.png'),full_page=True)
    dialog.get_by_role('button',name='Xác nhận import',exact=True).click()
    expect(page.get_by_role('link',name='Trần Thị Trang Tính',exact=True)).to_be_visible()
    page.set_viewport_size({'width':390,'height':844})
    page.screenshot(path=str(folder/'students-mobile.png'),full_page=True)
    assert page.evaluate('document.documentElement.scrollWidth <= innerWidth'), 'Horizontal page overflow'
    page.set_viewport_size({'width':1440,'height':1000})
    page.goto('http://localhost:5173/curriculum/versions/'+str(f['cloneVersionId'])+'/assessment-scheme')
    expect(page.get_by_role('heading',name='Cơ cấu điểm chung',exact=True)).to_be_visible()
    page.get_by_label('Tên đầu điểm 1',exact=True).fill('Quá trình theo CTĐT')
    page.get_by_role('button',name='Lưu cơ cấu điểm',exact=True).click()
    expect(page.get_by_role('status')).to_contain_text('Đã lưu cơ cấu điểm')
    page.screenshot(path=str(folder/'assessment-scheme-desktop.png'),full_page=True)
    assert not errors,errors
    browser.close()
print('PASS academic UI: six-digit course links, enroll, input grades/reload, Sheets preview/apply, shared assessment configuration, responsive roster and no JavaScript errors')
